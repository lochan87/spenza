/**
 * Returns a suggested category name based on the description, or null if no match.
 * Case-insensitive matching; longer keywords take precedence to reduce false matches.
 */
export function suggestCategory(description: string): string | null {
  const normalized = description.toLowerCase().trim();
  if (!normalized) return null;

  const keywords = Object.keys(CATEGORY_KEYWORDS).sort(
    (a, b) => b.length - a.length,
  );

  for (const keyword of keywords) {
    const escaped = keyword.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const pattern = new RegExp(`(^|[^a-z0-9])${escaped}($|[^a-z0-9])`, 'i');
    if (pattern.test(normalized)) {
      return CATEGORY_KEYWORDS[keyword];
    }
  }

  return null;
}
